// Makes real Groth16 proofs for the three test transactions and writes the
// same test vectors in the three formats the verifiers read:
//   fixtures/hashes.json, fixtures/proofs.json   (Rust tests, and humans)
//   evm/test/Fixtures.sol                        (Foundry tests)
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import * as snarkjs from "snarkjs";
import {
  initPoseidon, poseidon, zeroLeaf, zeroHashes, hex32, stringify, FIELD, LEVELS,
  PUBLIC_SIGNAL_NAMES, keccakField,
} from "./lib.mjs";
import { buildWorld, inputFor } from "./scenarios.mjs";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const WASM = path.join(root, "keys-dev/transaction2.wasm");
const ZKEY = path.join(root, "keys-dev/transaction2.zkey");
const VKEY = JSON.parse(fs.readFileSync(path.join(root, "keys-dev/verification_key.json"), "utf8"));

await initPoseidon();
const world = await buildWorld();

// ---- hash vectors: 1 to 4 inputs, including edge values --------------------
const edge = [0n, 1n, FIELD - 1n, keccakField("darkswap.test.vector")];
const vectors = [];
for (let arity = 1; arity <= 4; arity++) {
  for (let v = 0; v < 4; v++) {
    const inputs = Array.from({ length: arity }, (_, i) => edge[(v + i) % edge.length]);
    vectors.push({ inputs: inputs.map(hex32), out: hex32(poseidon(inputs)) });
  }
}
const zeros = zeroHashes(LEVELS);
const hashes = {
  field: hex32(FIELD),
  levels: LEVELS,
  zeroLeaf: hex32(zeroLeaf()),
  zeros: zeros.map(hex32),
  emptyRoot: hex32(zeros[LEVELS]),
  poseidon: vectors,
  tree: { leaves: world.leaves.map(hex32), root: hex32(world.tree.root) },
};

// ---- proofs ----------------------------------------------------------------
const proofs = [];
for (const scenario of world.scenarios) {
  const input = inputFor(scenario);
  const started = Date.now();
  const { proof, publicSignals } = await snarkjs.groth16.fullProve(stringify(input), WASM, ZKEY);
  const ms = Date.now() - started;
  if (!(await snarkjs.groth16.verify(VKEY, publicSignals, proof))) throw new Error("snarkjs rejected its own proof");

  // sanity: the public signals come out in the order the pools will pass them
  const expected = [input.root, input.publicAmount, input.extDataHash, input.publicAssetId,
    ...input.inputNullifier, ...input.outputCommitment];
  expected.forEach((v, i) => {
    if (BigInt(publicSignals[i]) !== v) throw new Error(`public signal ${PUBLIC_SIGNAL_NAMES[i]} out of order`);
  });

  proofs.push({
    name: scenario.name,
    proveMs: ms,
    // EVM / Solana layout: G1 = x,y. G2 = x.c1, x.c0, y.c1, y.c0.
    a: [proof.pi_a[0], proof.pi_a[1]].map(hex32),
    b: [proof.pi_b[0][1], proof.pi_b[0][0], proof.pi_b[1][1], proof.pi_b[1][0]].map(hex32),
    c: [proof.pi_c[0], proof.pi_c[1]].map(hex32),
    publicSignals: publicSignals.map(hex32),
  });
  console.log(`proved ${scenario.name} in ${ms} ms`);
}

fs.mkdirSync(path.join(root, "fixtures"), { recursive: true });
fs.writeFileSync(path.join(root, "fixtures/hashes.json"), JSON.stringify(hashes, null, 2));
fs.writeFileSync(path.join(root, "fixtures/proofs.json"),
  JSON.stringify({ publicSignalNames: PUBLIC_SIGNAL_NAMES, proofs }, null, 2));

// ---- Solidity fixtures -----------------------------------------------------
const u = (h) => `uint256(${h})`;
let sol = `// SPDX-License-Identifier: Apache-2.0
// GENERATED by scripts/gen-fixtures.mjs. Do not edit.
pragma solidity ^0.8.24;

library Fixtures {
    uint256 internal constant FIELD = ${hashes.field};
    uint256 internal constant ZERO_LEAF = ${hashes.zeroLeaf};
    uint256 internal constant EMPTY_ROOT = ${hashes.emptyRoot};
    uint256 internal constant TREE_ROOT = ${hashes.tree.root};
    uint256 internal constant VECTOR_COUNT = ${vectors.length};
    uint256 internal constant PROOF_COUNT = ${proofs.length};

    function leaves() internal pure returns (uint256[] memory out) {
        out = new uint256[](${world.leaves.length});
${hashes.tree.leaves.map((l, i) => `        out[${i}] = ${l};`).join("\n")}
    }

    function zeros() internal pure returns (uint256[] memory out) {
        out = new uint256[](${zeros.length});
${hashes.zeros.map((z, i) => `        out[${i}] = ${z};`).join("\n")}
    }

    function vector(uint256 i) internal pure returns (uint256[] memory inputs, uint256 out) {
${vectors.map((v, i) => `        if (i == ${i}) {
            inputs = new uint256[](${v.inputs.length});
${v.inputs.map((x, j) => `            inputs[${j}] = ${x};`).join("\n")}
            return (inputs, ${v.out});
        }`).join("\n")}
        revert("no such vector");
    }

    function proof(uint256 i)
        internal
        pure
        returns (uint256[2] memory a, uint256[2][2] memory b, uint256[2] memory c, uint256[8] memory pub)
    {
${proofs.map((p, i) => `        if (i == ${i}) {
            // ${p.name}
            a = [${p.a.map(u).join(", ")}];
            b = [[${u(p.b[0])}, ${u(p.b[1])}], [${u(p.b[2])}, ${u(p.b[3])}]];
            c = [${p.c.map(u).join(", ")}];
            pub = [
${p.publicSignals.map((s) => `                ${u(s)}`).join(",\n")}
            ];
            return (a, b, c, pub);
        }`).join("\n")}
        revert("no such proof");
    }
}
`;
fs.mkdirSync(path.join(root, "evm/test"), { recursive: true });
fs.writeFileSync(path.join(root, "evm/test/Fixtures.sol"), sol);
console.log(`wrote fixtures: ${vectors.length} hash vectors, ${proofs.length} proofs`);
process.exit(0);
